create table task_activity (
    id bigint generated by default as identity primary key,
    task_id bigint not null,
    task_name varchar(140) not null,
    category_id bigint not null,
    category_name varchar(60) not null,
    category_color varchar(7) not null,
    action varchar(20) not null,
    status varchar(30),
    previous_status varchar(30),
    occurred_at timestamp not null,
    note varchar(2000)
);
create index idx_task_activity_date on task_activity(occurred_at desc, id desc);
create index idx_task_activity_task on task_activity(task_id, occurred_at desc, id desc);

insert into task_activity (task_id, task_name, category_id, category_name, category_color, action, occurred_at)
select t.id, t.name, c.id, c.name, c.color, 'CREATED', t.created_at
from tasks t join categories c on c.id = t.category_id;

insert into task_activity (task_id, task_name, category_id, category_name, category_color, action, status, occurred_at, note)
select t.id, t.name, c.id, c.name, c.color, 'COMPLETED', 'COMPLETED', t.completed_at, t.completion_note
from tasks t join categories c on c.id = t.category_id
where t.completed_at is not null;

insert into task_activity (task_id, task_name, category_id, category_name, category_color, action, status, occurred_at, note)
select t.id, t.name, c.id, c.name, c.color, 'COMPLETED', 'COMPLETED', i.completed_at, i.completion_note
from task_iterations i join tasks t on t.id = i.task_id join categories c on c.id = t.category_id
where i.completed_at is not null and (i.iteration_number <> t.iteration or t.completed_at is null);
