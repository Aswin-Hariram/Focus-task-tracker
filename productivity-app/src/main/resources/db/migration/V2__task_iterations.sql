alter table tasks add column iteration integer not null default 1;
alter table progress_updates add column iteration integer not null default 1;

create table task_iterations (
    id bigint generated by default as identity primary key,
    task_id bigint not null references tasks(id) on delete cascade,
    iteration_number integer not null,
    started_at timestamp not null,
    completed_at timestamp,
    completion_note varchar(2000),
    created_at timestamp not null,
    updated_at timestamp not null
);

create index idx_task_iterations_task_id on task_iterations(task_id);
create index idx_progress_updates_iteration on progress_updates(task_id, iteration);
