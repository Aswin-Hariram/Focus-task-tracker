alter table tasks add column total_time_spent_seconds bigint not null default 0;
alter table tasks add column timer_status varchar(20) not null default 'STOPPED';
alter table tasks add column timer_started_at timestamp;
alter table tasks add column timer_accumulated_seconds bigint not null default 0;

create table task_time_logs (
    id bigint generated by default as identity primary key,
    task_id bigint not null references tasks(id) on delete cascade,
    started_at timestamp not null,
    ended_at timestamp not null,
    duration_seconds bigint not null,
    note varchar(500),
    created_at timestamp not null,
    updated_at timestamp not null
);

create index idx_task_time_logs_task_id on task_time_logs(task_id);
